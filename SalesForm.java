    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
  if (txtCustomerId.getText().trim().isEmpty()
        || txtEmployeeId.getText().trim().isEmpty()
        || txtSaleDate.getText().trim().isEmpty()
        || txtTotalAmount.getText().trim().isEmpty()) {

    JOptionPane.showMessageDialog(this, "Please fill all fields.");
    return;
}   try {
    Connection con = DriverManager.getConnection(
        "jdbc:mysql://localhost:3306/book_shop_db",
        "root",
        ""
    );

    String sql = "INSERT INTO sales "
            + "(customer_id, employee_id, sale_date, total_amount) "
            + "VALUES (?, ?, ?, ?)";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setInt(1, Integer.parseInt(txtCustomerId.getText()));
    pst.setInt(2, Integer.parseInt(txtEmployeeId.getText()));
    pst.setDate(3, java.sql.Date.valueOf(txtSaleDate.getText()));
    pst.setDouble(4, Double.parseDouble(txtTotalAmount.getText()));

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this, "Sale Added Successfully!");
    loadSales();

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}   // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

